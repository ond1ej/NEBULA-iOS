@Suite("Pairing links")
struct PairingLinkTests {
    let good = "nebula://pair?v=1&u=https%3A%2F%2Fnebula.example.ts.net&p=pr_0123456789abcdef" +
        "&c=AbCdEfGhIjKlMnOpQrStUv&f=fdad36166227f4287feb"

    @Test func parsesAValidLink() throws {
        let o = try #require(PairingOffer(link: good))
        #expect(o.gatewayURL.absoluteString == "https://nebula.example.ts.net")
        #expect(o.pairingID == "pr_0123456789abcdef")
        #expect(o.code == "AbCdEfGhIjKlMnOpQrStUv")
        #expect(o.fingerprint == "fdad36166227f4287feb")
    }

    @Test(arguments: [
        "https://evil.example/pair?v=1",  // wrong scheme
        "nebula://pair?v=2&u=https%3A%2F%2Fa.b&p=pr_0123456789abcdef&c=AbCdEfGhIjKlMnOpQrStUv&f=fdad36166227f4287feb",
        "nebula://pair?v=1&u=http%3A%2F%2Fa.b&p=pr_0123456789abcdef&c=AbCdEfGhIjKlMnOpQrStUv&f=fdad36166227f4287feb",
        "nebula://pair?v=1&u=https%3A%2F%2Fa.b&p=pr_XYZ&c=AbCdEfGhIjKlMnOpQrStUv&f=fdad36166227f4287feb",
        "nebula://pair?v=1&u=https%3A%2F%2Fa.b&p=pr_0123456789abcdef&c=short&f=fdad36166227f4287feb",
        "nebula://pair?v=1&u=https%3A%2F%2Fa.b&p=pr_0123456789abcdef&c=AbCdEfGhIjKlMnOpQrStUv&f=nothex",
    ])
    func rejectsBadLinks(_ link: String) {
        #expect(PairingOffer(link: link) == nil)
    }
}

@Suite("Server signatures (Python cryptography ↔ CryptoKit)")
struct ServerSignatureTests {
    // generated by the server's own primitives (cryptography: X9.62 uncompressed point, DER ECDSA/SHA-256)
    let pub = "BOYQcrkCswNzOr5ohJgIWMmm4SMYQYyjToNDLc+eNfmyfRbfdmbJnFGOsnw6nU3ilLbCdmDRKQiPZQXwv57mVIg="
    let sig = "MEUCIG6E8ZjqPzelwRQukH60i/25XU/cs2hiTGHvwVm2D71vAiEAohMYssvMA24TdzwJHIKNEPCwmMagYbJbz1lblBqYGAw="

    var payload: Data {
        Data(["nebula-app-pair-ack/v1", "pr_0123456789abcdef", "adv_0011223344556677",
              DeviceKeys.sha256Hex(Data("IDKEY".utf8))].joined(separator: "\n").utf8)
    }

    @Test func verifiesAServerSignature() {
        #expect(PairingService.verify(serverKey: pub, payload: payload, signature: sig))
        #expect(PairingService.fingerprint(of: pub) == "fdad36166227f4287feb")
    }

    @Test func rejectsATamperedPayloadOrKey() {
        var bad = payload
        bad.append(0x20)
        #expect(!PairingService.verify(serverKey: pub, payload: bad, signature: sig))
        let other = P256.Signing.PrivateKey().publicKey.x963Representation.base64EncodedString()
        #expect(!PairingService.verify(serverKey: other, payload: payload, signature: sig))
        #expect(!PairingService.verify(serverKey: "not base64", payload: payload, signature: sig))
    }

    /// The other direction (what the app signs, the server accepts) is checked by the server's own test suite with a
    /// CryptoKit-made vector: tests/unit/test_v40_crypto_vectors.py — and end to end by the UI tests.
    @Test func signatureFormatMatchesTheServer() throws {
        let key = P256.Signing.PrivateKey()
        #expect(key.publicKey.x963Representation.count == 65 && key.publicKey.x963Representation.first == 4)
        let sig = try key.signature(for: Data("x".utf8)).derRepresentation
        #expect(sig.first == 0x30)  // DER SEQUENCE, as cryptography's ECDSA verify expects
        #expect(DeviceKeys.sha256Hex(Data(repeating: 7, count: 32)) ==
                "4bb06f8e4e3a7715d201d573d0aa423762e55dabd61a2c02278fa56cc6d294e0")
    }
}

@Suite("Server compatibility")
struct CompatibilityTests {
    @Test func acceptsTheSupportedGatewayProtocol() {
        #expect(PairingService.isCompatible(api: 4))
    }

    @Test(arguments: [0, 1, 3, 5, 99, -1])
    func refusesOtherGatewayProtocols(_ api: Int) {
        #expect(!PairingService.isCompatible(api: api))
    }

    @Test func theMessageNamesBothProtocolLevels() {
        let text = PairingError.incompatibleServer(api: 7).errorDescription ?? ""
        #expect(text.contains("7") && text.contains("4"))
    }
}
